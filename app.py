def add_numbers(a,b):
    return a+b

def subtract_numbers(a,b):
    return a-b

def multiply_numbers(a,b):
    return a*b

def main():
    result = add_numbers(10,20)
    print(f"SUM :{result}")
    result1 = subtract_numbers(10,20)
    print(f"SUBSTRACTION :{result1}")
    result2 = multiply_numbers(10,20)
    print(f"SUBSTRACTION :{result2}")

if __name__ == "__main__":
    main()
